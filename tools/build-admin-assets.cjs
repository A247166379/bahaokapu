#!/usr/bin/env node
'use strict';

// Development-only asset generator. This is never an HTTP entry point.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');

function options(args) {
    const result = {root: path.resolve(__dirname, '..'), check: false};
    for (let index = 0; index < args.length; index++) {
        const value = args[index];
        if (value === '--check') result.check = true;
        else if (value === '--help') result.help = true;
        else if (value === '--root') {
            assert(args[index + 1] && !args[index + 1].startsWith('--'), '--root requires a directory');
            result.root = path.resolve(args[++index]);
        } else if (value.startsWith('--root=')) {
            assert(value.slice(7), '--root requires a directory');
            result.root = path.resolve(value.slice(7));
        } else throw new Error('Unknown argument: ' + value);
    }
    return result;
}

async function build(settings) {
    const {minify} = require('terser');
    const CleanCSS = require('clean-css');
    const acorn = require('acorn');
    const dependencies = JSON.parse(fs.readFileSync(path.join(__dirname, 'admin-assets.package.json'), 'utf8')).dependencies;
    for (const [name, version] of Object.entries(dependencies)) {
        assert.equal(require(name + '/package.json').version, version, name + ' must match the pinned build version');
    }

    const read = file => fs.readFileSync(path.join(settings.root, file), 'utf8');
    const minifyOptions = {compress: true, mangle: true, format: {comments: false}};
    const common = read('assets/common/js/_.js');
    const matches = acorn.parse(common, {ecmaVersion: 'latest'}).body
        .filter(node => node.type === 'ClassDeclaration' && node.id?.name === 'Form');
    assert.equal(matches.length, 1, 'The common bundle must contain exactly one top-level Form class');
    const form = await minify(read('assets/common/js/component/form.js'), minifyOptions);
    assert(form.code, 'Form minification produced no code');
    const material = await minify(read('assets/admin/js/material.js'), minifyOptions);
    assert(material.code, 'Material minification produced no code');
    // Keep the established CSS source order. md-icons is a separate asset, not part of this bundle.
    const cssSources = ['assets/common/css/md-tokens.css', 'assets/common/css/md-components.css'];
    const css = new CleanCSS({level: 1}).minify(cssSources.map(read).join('\n'));
    assert.deepEqual(css.errors, [], 'CSS minification failed');

    const node = matches[0];
    // The original common bundle contains third-party code. Replace only its Form class.
    const generated = new Map([
        ['assets/common/js/_.js', common.slice(0, node.start) + form.code + common.slice(node.end)],
        ['assets/admin/js/_material.js', material.code + '\n'],
        ['assets/common/css/_material.css', css.styles + '\n'],
    ]);
    const files = [];
    for (const [file, output] of generated) {
        const bytes = Buffer.from(output, 'utf8');
        const unchanged = fs.readFileSync(path.join(settings.root, file)).equals(bytes);
        if (!settings.check && !unchanged) fs.writeFileSync(path.join(settings.root, file), bytes);
        files.push({file, bytes: bytes.length, sha256: crypto.createHash('sha256').update(bytes).digest('hex'), unchanged});
    }
    console.log(JSON.stringify({mode: settings.check ? 'check' : 'build', files, cssWarnings: css.warnings}, null, 2));
    if (settings.check && files.some(file => !file.unchanged)) process.exitCode = 1;
}

(async () => {
    const settings = options(process.argv.slice(2));
    if (settings.help) {
        console.log('Usage: node tools/build-admin-assets.cjs [--root DIRECTORY] [--check]\nDefault root: parent directory of tools. --check compares generated bytes without writing.');
        return;
    }
    await build(settings);
})().catch(error => {
    console.error(error.message);
    process.exitCode = 1;
});
